export function pickCurrentGlobalSettings(value: unknown): Partial<GlobalSettings> {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    return {}
  }
  return Object.fromEntries(
    Object.keys(CURRENT_GLOBAL_SETTING_KEYS)
      .filter((key) => Object.hasOwn(value, key) && Reflect.get(value, key) !== undefined)
      .map((key) => [key, Reflect.get(value, key)])
  )
}
